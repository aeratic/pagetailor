import { cp, mkdir, access, readFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { writeRegistryFile } from "./registry-file.js";

const here = dirname(fileURLToPath(import.meta.url));

export async function init(cwd, args = []) {
  const target = join(cwd, "pagetailor");
  const force = args.includes("--force");
  try { await access(target); if (!force) throw new Error("pagetailor/ already exists (use --force to overwrite)"); } catch (e) { if (e.code !== "ENOENT") throw e; }
  await mkdir(target, { recursive: true });
  await cp(join(here, "..", "templates"), target, { recursive: true, force });
  await writeRegistryFile(cwd);
  let needs = [];
  try {
    const pkg = JSON.parse(await readFile(join(cwd, "package.json"), "utf8"));
    const deps = { ...pkg.dependencies, ...pkg.devDependencies };
    for (const d of ["@aeratic/pagetailor", "react", "react-dom"]) if (!deps[d]) needs.push(d);
  } catch { needs = ["@aeratic/pagetailor", "react", "react-dom"]; }
  console.log(`created ${target}/
  manifest.yaml           app shape: pages, home, navigation, roles
  tokens.yaml             design tokens, exposed as CSS variables --pt-*
  data-catalog.yaml       typed data sources with roles
  data/sources.mjs         one async function per source (demo data, replace with your APIs)
  pages/home.yaml         a sample page: card > grid with named areas
  overrides/              per-user (user-giulia) and per-role (role-magazzino) patches
  components/             registry.yaml + 9 base components, yours to edit; index.js generated by "pagetailor registry"
`);
  if (needs.length) console.log(`install the runtime:\n  npm install ${needs.join(" ")}\n`);
  console.log(`then:\n  npx pagetailor validate\n  npx pagetailor dev`);
}
