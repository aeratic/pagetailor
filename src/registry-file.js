import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { loadYaml } from "./loader.js";

// Writes pagetailor/components/index.js: imports every impl in registry.yaml, exports { "name@version": Component }.
export async function writeRegistryFile(cwd) {
  const dir = join(cwd, "pagetailor", "components");
  const reg = await loadYaml(join(dir, "registry.yaml"));
  const entries = [];
  for (const [name, def] of Object.entries(reg ?? {})) for (const [ver, v] of Object.entries(def.versions ?? {}))
    if (v.impl) entries.push([`${name}@${ver}`, v.impl.startsWith(".") ? v.impl : `./${v.impl}`]);
  entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  const src = `// generated by \`pagetailor registry\`, do not edit
${entries.map(([, impl], i) => `import C${i} from ${JSON.stringify(impl)};`).join("\n")}

export const registry = {
${entries.map(([key], i) => `  ${JSON.stringify(key)}: C${i},`).join("\n")}
};
export default registry;
`;
  const out = join(dir, "index.js");
  await writeFile(out, src);
  return { path: out, count: entries.length };
}
